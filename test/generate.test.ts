import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { mkdtemp, rm, readFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generateAgentFiles, diffAgentFiles, cleanAgentDirs } from "../src/generate.js";
import { getAgent } from "../src/agents.js";
import { SKILLS_SRC } from "../src/paths.js";

const claude = getAgent("claude")!;
const kiro = getAgent("kiro")!;
const cursor = getAgent("cursor")!;

let dir: string;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "halyard-gen-"));
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

async function skillCount(): Promise<number> {
  const entries = await readdir(SKILLS_SRC, { withFileTypes: true });
  return entries.filter((e) => e.isDirectory()).length;
}

describe("generateAgentFiles", () => {
  it("writes one file per skill plus the command defs, per agent", async () => {
    const res = await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const skills = await skillCount();
    // skills + commands all written, none skipped on a clean dir
    expect(res.written.length).toBeGreaterThanOrEqual(skills);
    expect(res.skipped).toHaveLength(0);
    // claude skills land in .claude/skills
    expect(existsSync(join(dir, ".claude/skills"))).toBe(true);
  });

  it("lays Claude skills out as <name>/SKILL.md (dir layout), not flat files", async () => {
    // regression: flat .claude/skills/<name>.md does NOT register as a Claude Agent Skill
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    expect(existsSync(join(dir, ".claude/skills/github/SKILL.md"))).toBe(true);
    expect(existsSync(join(dir, ".claude/skills/solutions/SKILL.md"))).toBe(true);
    // the old flat form must NOT be present
    expect(existsSync(join(dir, ".claude/skills/github.md"))).toBe(false);
  });

  it("lays Cursor skills out as .cursor/skills/<name>/SKILL.md (Agent Skills spec)", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [cursor], force: false });
    expect(existsSync(join(dir, ".cursor/skills/github/SKILL.md"))).toBe(true);
  });

  it("every agent uses the <name>/SKILL.md dir layout under its skills dir", async () => {
    const amazonq = getAgent("amazonq")!;
    await generateAgentFiles({ projectRoot: dir, agents: [amazonq], force: false });
    expect(existsSync(join(dir, ".amazonq/skills/github/SKILL.md"))).toBe(true);
    // no flat form anywhere
    expect(existsSync(join(dir, ".amazonq/skills/github.md"))).toBe(false);
  });

  it("stamps the do-not-edit header on generated skill files", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const body = await readFile(join(dir, ".claude/skills/github/SKILL.md"), "utf8");
    expect(body).toContain("generated by halyard — do not edit");
  });

  it("keeps YAML frontmatter valid — header goes AFTER it, not above line 1", async () => {
    // regression: a leading HTML comment makes the parser miss the frontmatter, so
    // name/description are lost and the skill can't auto-trigger.
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const body = await readFile(join(dir, ".claude/skills/github/SKILL.md"), "utf8");
    // frontmatter must open on line 1
    expect(body.startsWith("---\n")).toBe(true);
    // the notice must sit AFTER the closing --- of the frontmatter
    const fmEnd = body.indexOf("\n---", 4);
    const noticeAt = body.indexOf("generated by halyard");
    expect(fmEnd).toBeGreaterThan(0);
    expect(noticeAt).toBeGreaterThan(fmEnd);
    // name/description still parse as the first frontmatter keys
    const front = body.slice(0, body.indexOf("\n---", 4));
    expect(front).toContain("name: github");
    expect(front).toContain("description:");
  });

  it("substitutes {{AIDLC_ROOT}} with halyard/rules and leaves no raw token", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const skillDirs = await readdir(join(dir, ".claude/skills"));
    for (const d of skillDirs) {
      const f = join(dir, ".claude/skills", d, "SKILL.md");
      if (!existsSync(f)) continue;
      const body = await readFile(f, "utf8");
      expect(body).not.toContain("{{AIDLC_ROOT}}");
    }
    const solutions = await readFile(join(dir, ".claude/skills/solutions/SKILL.md"), "utf8");
    expect(solutions).toContain("halyard/rules/");
  });

  it("does not leak the old .claude-dialect docs/templates path (stale-path regression)", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const skillDirs = await readdir(join(dir, ".claude/skills"));
    for (const d of skillDirs) {
      const f = join(dir, ".claude/skills", d, "SKILL.md");
      if (!existsSync(f)) continue;
      const body = await readFile(f, "utf8");
      expect(body).not.toContain("docs/templates/");
    }
  });

  it("skips existing files when force is false, overwrites when true", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const second = await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    expect(second.written).toHaveLength(0);
    expect(second.skipped.length).toBeGreaterThan(0);

    const forced = await generateAgentFiles({ projectRoot: dir, agents: [claude], force: true });
    expect(forced.written.length).toBeGreaterThan(0);
    expect(forced.skipped).toHaveLength(0);
  });

  it("writes to each agent's own directory for multiple agents", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude, kiro], force: false });
    expect(existsSync(join(dir, ".claude/skills"))).toBe(true);
    expect(existsSync(join(dir, ".kiro/skills"))).toBe(true);
  });

  it("writes slash-commands to the agent's command location with a halyard/ namespace subdir", async () => {
    // regression: commands used to land in .claude/skills/commands, which Claude Code
    // does NOT scan for slash commands — so /hyd:install never appeared.
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    // Claude slash commands come from .claude/commands; the halyard/ subdir yields /hyd:install
    expect(existsSync(join(dir, ".claude/commands/hyd/install.md"))).toBe(true);
    expect(existsSync(join(dir, ".claude/commands/hyd/intent.md"))).toBe(true);
    // and NOT in the old (wrong) place
    expect(existsSync(join(dir, ".claude/skills/commands"))).toBe(false);
  });
});

describe("diffAgentFiles", () => {
  it("reports no drift immediately after a clean generate", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const drift = await diffAgentFiles({ projectRoot: dir, agents: [claude], force: true });
    expect(drift).toEqual([]);
  });

  it("flags a hand-edited file", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    const { writeFile } = await import("node:fs/promises");
    await writeFile(join(dir, ".claude/skills/github/SKILL.md"), "tampered", "utf8");
    const drift = await diffAgentFiles({ projectRoot: dir, agents: [claude], force: true });
    expect(drift.some((d) => d.includes("github"))).toBe(true);
  });

  it("flags a missing file", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    await rm(join(dir, ".claude/skills/github/SKILL.md"));
    const drift = await diffAgentFiles({ projectRoot: dir, agents: [claude], force: true });
    expect(drift.some((d) => d.includes("github") && d.includes("missing"))).toBe(true);
  });
});

describe("cleanAgentDirs", () => {
  it("removes the generated halyard command dir without touching skills", async () => {
    await generateAgentFiles({ projectRoot: dir, agents: [claude], force: false });
    // Claude commands live under .claude/commands/hyd (a slash-command location),
    // NOT under .claude/skills.
    expect(existsSync(join(dir, ".claude/commands/hyd"))).toBe(true);
    await cleanAgentDirs(dir, [claude]);
    expect(existsSync(join(dir, ".claude/commands/hyd"))).toBe(false);
    // skills untouched (dir layout: <name>/SKILL.md)
    expect(existsSync(join(dir, ".claude/skills/github/SKILL.md"))).toBe(true);
  });
});
