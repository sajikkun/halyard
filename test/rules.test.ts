import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { mkdtemp, rm, readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { syncRules, diffRules } from "../src/scaffold.js";
import { RULES_SRC } from "../src/paths.js";

let dir: string;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "nvaid-rules-"));
  await mkdir(join(dir, "nvaid"), { recursive: true });
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

describe("syncRules", () => {
  it("writes every source rule file into nvaid/rules", async () => {
    await syncRules(dir);
    const srcNames = (await readdir(RULES_SRC)).sort();
    const outNames = (await readdir(join(dir, "nvaid/rules"))).sort();
    expect(outNames).toEqual(srcNames);
  });

  it("stamps the do-not-edit header on each rule file", async () => {
    await syncRules(dir);
    for (const name of await readdir(join(dir, "nvaid/rules"))) {
      const body = await readFile(join(dir, "nvaid/rules", name), "utf8");
      expect(body).toContain("generated by nvaid — do not edit");
    }
  });

  it("keeps rule-file frontmatter valid — header after the --- block, not line 1", async () => {
    await syncRules(dir);
    // family-rules.md and the contract-gen rules open with YAML frontmatter
    const body = await readFile(join(dir, "nvaid/rules/family-rules.md"), "utf8");
    expect(body.startsWith("---\n")).toBe(true);
    const fmEnd = body.indexOf("\n---", 4);
    const noticeAt = body.indexOf("generated by nvaid");
    expect(fmEnd).toBeGreaterThan(0);
    expect(noticeAt).toBeGreaterThan(fmEnd);
  });

  it("ships family-rules.md (G1) with rules 11–16", async () => {
    await syncRules(dir);
    const fr = await readFile(join(dir, "nvaid/rules/family-rules.md"), "utf8");
    for (const n of ["11.", "12.", "13.", "14.", "15.", "16."]) {
      expect(fr).toContain(n);
    }
    // rule 11 is GitHub-Projects-only: it names GitHub Projects/Milestones as the tracker.
    // (It may still mention Jira to state explicitly that the family does NOT use it.)
    expect(fr).toContain("GitHub");
    expect(fr).toMatch(/Milestone/);
  });
});

describe("diffRules", () => {
  it("reports no drift immediately after syncRules", async () => {
    await syncRules(dir);
    expect(await diffRules(dir)).toEqual([]);
  });

  it("flags a hand-edited rule file (the Catch-1 gap)", async () => {
    await syncRules(dir);
    await writeFile(join(dir, "nvaid/rules/family-rules.md"), "tampered", "utf8");
    const drift = await diffRules(dir);
    expect(drift.some((d) => d.includes("family-rules.md"))).toBe(true);
  });

  it("flags a missing rule file", async () => {
    await syncRules(dir);
    await rm(join(dir, "nvaid/rules/unit-breakdown-rules.md"));
    const drift = await diffRules(dir);
    expect(drift.some((d) => d.includes("unit-breakdown-rules.md") && d.includes("missing"))).toBe(true);
  });
});
